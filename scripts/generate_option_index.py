"""Generate a searchable option index from the primary source's API comments."""

from __future__ import annotations

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "docs/OPTIONS.md"


def escape_mdx(text: str) -> str:
    # Keep inline code intact; braces and angle brackets in prose are literal data.
    parts = re.split(r"(`[^`]*`)", text)
    for index in range(0, len(parts), 2):
        parts[index] = parts[index].replace("{", "\\{").replace("}", "\\}").replace("<", "&lt;").replace(">", "&gt;")
    return "".join(parts)


def render() -> str:
    source = (ROOT / "saveinstance.luau").read_text(encoding="utf-8")
    section = source.split("--- @interface CustomOptions table", 1)[1].split("--- @interface OptionsAliases", 1)[0]
    lines = [
        "---", "sidebar_position: 3", "title: Option index", "---", "", "# Option index", "",
        "<!-- Generated by scripts/generate_option_index.py from saveinstance.luau. -->", "",
        "Searchable names, types, descriptions, and defaults extracted from the primary source.",
        "These describe the implementation; they do not establish runtime compatibility.", "",
        "See the [full API reference](/api/CompleteSaveInstance) for aliases and function signatures.",
        "Preset overrides are listed in [Script Presets](PRESETS.md).", "",
    ]
    for name, kind, description in re.findall(r"^--- (?:@field |\.)(\w+)\s+(.+?)\s*--(.*)$", section, re.MULTILINE):
        description, default = re.split(r"___Default:___\s*", description, maxsplit=1)
        lines += [f"## {name}", "", f"Type: `{kind.strip()}`. Source default: `{default.strip().strip('`')}`.", ""]
        if description.strip():
            lines += [escape_mdx(description.strip()), ""]
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rendered = render()
    if args.check:
        if not TARGET.is_file() or TARGET.read_text(encoding="utf-8") != rendered:
            raise SystemExit("Regenerate the option index: python scripts/generate_option_index.py")
        print("Source-generated option index is current.")
    else:
        TARGET.write_text(rendered, encoding="utf-8", newline="\n")
        print("Generated searchable option index.")
